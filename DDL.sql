  PUNTOS_OBTENIDOS       NUMBER(3)       NOT NULL,
  OBSERVACIONES          VARCHAR2(300),
  TIEMPO_EJECUCION       NUMBER(10),
  CONSTRAINT PK_DETALLE_PRACTICO PRIMARY KEY (ID_DETALLE_PRACTICO),
  CONSTRAINT FK_DET_PRAC_EVAL FOREIGN KEY (ID_EVALUACION) 
    REFERENCES EVALUACION(ID_EVALUACION) ON DELETE CASCADE,
  CONSTRAINT FK_DET_PRAC_PREG FOREIGN KEY (ID_PREGUNTA_PRACTICA) 
    REFERENCES PREGUNTA_PRACTICA(ID_PREGUNTA_PRACTICA),
  CONSTRAINT CK_DET_PRAC_PUNTOS CHECK (PUNTOS_OBTENIDOS BETWEEN 0 AND 20),
  CONSTRAINT UQ_DET_PRAC_EVAL_PREG UNIQUE (ID_EVALUACION, ID_PREGUNTA_PRACTICA)
);

