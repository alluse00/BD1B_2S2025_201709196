-- Tabla: DEPARTAMENTO
CREATE TABLE DEPARTAMENTO (
  ID_DEPARTAMENTO        NUMBER(10)      NOT NULL,
  NOMBRE                 VARCHAR2(50)    NOT NULL,
  CODIGO                 VARCHAR2(3)     NOT NULL UNIQUE,
  CONSTRAINT PK_DEPARTAMENTO PRIMARY KEY (ID_DEPARTAMENTO)
);

-- Tabla: MUNICIPIO
CREATE TABLE MUNICIPIO (
  ID_MUNICIPIO           NUMBER(10)      NOT NULL,
  ID_DEPARTAMENTO        NUMBER(10)      NOT NULL,
  NOMBRE                 VARCHAR2(50)    NOT NULL,
  CODIGO                 VARCHAR2(5)     NOT NULL,
  CONSTRAINT PK_MUNICIPIO PRIMARY KEY (ID_MUNICIPIO),
  CONSTRAINT FK_MUNICIPIO_DEPTO FOREIGN KEY (ID_DEPARTAMENTO) 
    REFERENCES DEPARTAMENTO(ID_DEPARTAMENTO),
  CONSTRAINT UQ_MUNICIPIO_CODIGO UNIQUE (ID_DEPARTAMENTO, CODIGO)
);

-- Tabla: TIPO_LICENCIA
CREATE TABLE TIPO_LICENCIA (
  ID_TIPO_LICENCIA       NUMBER(10)      NOT NULL,
  CODIGO                 CHAR(1)         NOT NULL UNIQUE,
  DESCRIPCION            VARCHAR2(50)    NOT NULL,
  REQUISITOS             VARCHAR2(500),
  CONSTRAINT PK_TIPO_LICENCIA PRIMARY KEY (ID_TIPO_LICENCIA),
  CONSTRAINT CK_TIPO_LIC_CODIGO CHECK (CODIGO IN ('M', 'P', 'B', 'A', 'E'))
);

-- Tabla: TIPO_TRAMITE
CREATE TABLE TIPO_TRAMITE (
  ID_TIPO_TRAMITE        NUMBER(10)      NOT NULL,
  DESCRIPCION            VARCHAR2(50)    NOT NULL,
  CODIGO                 VARCHAR2(10)    NOT NULL UNIQUE,
  CONSTRAINT PK_TIPO_TRAMITE PRIMARY KEY (ID_TIPO_TRAMITE)
);

