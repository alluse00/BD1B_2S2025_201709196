-- Tabla: RESPUESTA_TEORICA
CREATE TABLE RESPUESTA_TEORICA (
  ID_RESPUESTA           NUMBER(10)      NOT NULL,
  ID_PREGUNTA            NUMBER(10)      NOT NULL,
  TEXTO_RESPUESTA        VARCHAR2(500)   NOT NULL,
  IMAGEN_RESPUESTA       VARCHAR2(255),
  ES_CORRECTA            NUMBER(1)       NOT NULL,
  ORDEN_RESPUESTA        CHAR(1)         NOT NULL,
  CONSTRAINT PK_RESPUESTA_TEORICA PRIMARY KEY (ID_RESPUESTA),
  CONSTRAINT FK_RESPUESTA_PREGUNTA FOREIGN KEY (ID_PREGUNTA) 
    REFERENCES PREGUNTA_TEORICA(ID_PREGUNTA) ON DELETE CASCADE,
  CONSTRAINT CK_RESPUESTA_CORRECTA CHECK (ES_CORRECTA IN (0, 1)),
  CONSTRAINT CK_RESPUESTA_ORDEN CHECK (ORDEN_RESPUESTA IN ('A', 'B', 'C', 'D')),
  CONSTRAINT UQ_RESPUESTA_ORDEN UNIQUE (ID_PREGUNTA, ORDEN_RESPUESTA)
