-- Tabla: PREGUNTA_TEORICA
CREATE TABLE PREGUNTA_TEORICA (
  ID_PREGUNTA            NUMBER(10)      NOT NULL,
  TEXTO_PREGUNTA         VARCHAR2(1000)  NOT NULL,
  IMAGEN_PREGUNTA        VARCHAR2(255),
  ID_TIPO_LICENCIA       NUMBER(10)      NOT NULL,
  CATEGORIA              VARCHAR2(50),
  NIVEL_DIFICULTAD       VARCHAR2(10) DEFAULT 'MEDIO',
  ESTADO                 CHAR(1) DEFAULT 'A' NOT NULL,
  FECHA_REGISTRO         DATE DEFAULT SYSDATE NOT NULL,
  USUARIO_REGISTRO       VARCHAR2(50)    NOT NULL,
  CONSTRAINT PK_PREGUNTA_TEORICA PRIMARY KEY (ID_PREGUNTA),
  CONSTRAINT FK_PREGUNTA_TIPO_LIC FOREIGN KEY (ID_TIPO_LICENCIA) 
    REFERENCES TIPO_LICENCIA(ID_TIPO_LICENCIA),
  CONSTRAINT CK_PREGUNTA_ESTADO CHECK (ESTADO IN ('A', 'I')),
  CONSTRAINT CK_PREGUNTA_NIVEL CHECK (NIVEL_DIFICULTAD IN ('FACIL', 'MEDIO', 'DIFICIL'))
