-- Tabla: CENTRO_EVALUACION
CREATE TABLE CENTRO_EVALUACION (
  ID_CENTRO              NUMBER(10)      NOT NULL,
  NOMBRE                 VARCHAR2(100)   NOT NULL,
  DIRECCION              VARCHAR2(200)   NOT NULL,
  TELEFONO               VARCHAR2(15),
  EMAIL                  VARCHAR2(100),
  ID_MUNICIPIO           NUMBER(10)      NOT NULL,
  FECHA_REGISTRO         DATE DEFAULT SYSDATE NOT NULL,
  USUARIO_REGISTRO       VARCHAR2(50)    NOT NULL,
  ESTADO                 CHAR(1) DEFAULT 'A' NOT NULL,
  CONSTRAINT PK_CENTRO_EVALUACION PRIMARY KEY (ID_CENTRO),
  CONSTRAINT FK_CENTRO_MUNICIPIO FOREIGN KEY (ID_MUNICIPIO)
    REFERENCES MUNICIPIO(ID_MUNICIPIO),
  CONSTRAINT CK_CENTRO_ESTADO CHECK (ESTADO IN ('A', 'I'))
);

-- Tabla: ESCUELA_AUTOMOVILISMO
CREATE TABLE ESCUELA_AUTOMOVILISMO (
  ID_ESCUELA             NUMBER(10)      NOT NULL,
  NOMBRE                 VARCHAR2(100)   NOT NULL,
  DIRECCION              VARCHAR2(200)   NOT NULL,
  NUMERO_AUTORIZACION    VARCHAR2(20)    NOT NULL UNIQUE,
  TELEFONO               VARCHAR2(15),
  EMAIL                  VARCHAR2(100),
  ID_MUNICIPIO           NUMBER(10)      NOT NULL,
  FECHA_REGISTRO         DATE DEFAULT SYSDATE NOT NULL,
  USUARIO_REGISTRO       VARCHAR2(50)    NOT NULL,
  ESTADO                 CHAR(1) DEFAULT 'A' NOT NULL,
  CONSTRAINT PK_ESCUELA_AUTO PRIMARY KEY (ID_ESCUELA),
  CONSTRAINT FK_ESCUELA_MUNICIPIO FOREIGN KEY (ID_MUNICIPIO)
    REFERENCES MUNICIPIO(ID_MUNICIPIO),
  CONSTRAINT CK_ESCUELA_ESTADO CHECK (ESTADO IN ('A', 'I'))
);

-- Tabla: CENTRO_ESCUELA (Relación N:M)
CREATE TABLE CENTRO_ESCUELA (
  ID_CENTRO              NUMBER(10)      NOT NULL,
  ID_ESCUELA             NUMBER(10)      NOT NULL,
  FECHA_INICIO           DATE            NOT NULL,
  FECHA_FIN              DATE,
  USUARIO_REGISTRO       VARCHAR2(50)    NOT NULL,
  CONSTRAINT PK_CENTRO_ESCUELA PRIMARY KEY (ID_CENTRO, ID_ESCUELA),
  CONSTRAINT FK_CE_CENTRO FOREIGN KEY (ID_CENTRO) 
    REFERENCES CENTRO_EVALUACION(ID_CENTRO),
  CONSTRAINT FK_CE_ESCUELA FOREIGN KEY (ID_ESCUELA) 
    REFERENCES ESCUELA_AUTOMOVILISMO(ID_ESCUELA),
  CONSTRAINT CK_CE_FECHAS CHECK (FECHA_FIN IS NULL OR FECHA_FIN >= FECHA_INICIO)
);

