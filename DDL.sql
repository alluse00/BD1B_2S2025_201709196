-- Tabla: EVALUACION
CREATE TABLE EVALUACION (
  ID_EVALUACION          NUMBER(10)      NOT NULL,
  CORRELATIVO_DIARIO     NUMBER(10)      NOT NULL,
  ID_PERSONA             NUMBER(10)      NOT NULL,
  ID_CENTRO              NUMBER(10)      NOT NULL,
  ID_ESCUELA             NUMBER(10)      NOT NULL,
  ID_TIPO_LICENCIA       NUMBER(10)      NOT NULL,
  ID_TIPO_TRAMITE        NUMBER(10)      NOT NULL,
  FECHA_EVALUACION       DATE            NOT NULL,
  HORA_INICIO            TIMESTAMP       NOT NULL,
  HORA_FIN               TIMESTAMP,
  PUNTAJE_TEORICO        NUMBER(3) DEFAULT 0,
  PUNTAJE_PRACTICO       NUMBER(3) DEFAULT 0,
  PUNTAJE_TOTAL          NUMBER(3) DEFAULT 0,
  RESULTADO_FINAL        CHAR(1),
  ID_INSTRUCTOR          NUMBER(10)      NOT NULL,
  OBSERVACIONES          VARCHAR2(500),
  FECHA_REGISTRO         TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  USUARIO_REGISTRO       VARCHAR2(50)    NOT NULL,
  CONSTRAINT PK_EVALUACION PRIMARY KEY (ID_EVALUACION),
  CONSTRAINT FK_EVAL_PERSONA FOREIGN KEY (ID_PERSONA) 
    REFERENCES PERSONA(ID_PERSONA),
  CONSTRAINT FK_EVAL_CENTRO FOREIGN KEY (ID_CENTRO) 
    REFERENCES CENTRO_EVALUACION(ID_CENTRO),
  CONSTRAINT FK_EVAL_ESCUELA FOREIGN KEY (ID_ESCUELA) 
    REFERENCES ESCUELA_AUTOMOVILISMO(ID_ESCUELA),
  CONSTRAINT FK_EVAL_TIPO_LIC FOREIGN KEY (ID_TIPO_LICENCIA) 
    REFERENCES TIPO_LICENCIA(ID_TIPO_LICENCIA),
  CONSTRAINT FK_EVAL_TIPO_TRAM FOREIGN KEY (ID_TIPO_TRAMITE) 
    REFERENCES TIPO_TRAMITE(ID_TIPO_TRAMITE),
  CONSTRAINT FK_EVAL_INSTRUCTOR FOREIGN KEY (ID_INSTRUCTOR) 
    REFERENCES INSTRUCTOR(ID_INSTRUCTOR),
  CONSTRAINT CK_EVAL_RESULTADO CHECK (RESULTADO_FINAL IN ('A', 'R')),
  CONSTRAINT CK_EVAL_PUNTAJES CHECK (
    PUNTAJE_TEORICO BETWEEN 0 AND 100 AND
    PUNTAJE_PRACTICO BETWEEN 0 AND 100 AND
    PUNTAJE_TOTAL BETWEEN 0 AND 100
  ),
  CONSTRAINT UQ_EVAL_CORRELATIVO UNIQUE (ID_CENTRO, FECHA_EVALUACION, CORRELATIVO_DIARIO)
);

-- Tabla: DETALLE_EVALUACION_TEORICA
CREATE TABLE DETALLE_EVALUACION_TEORICA (
  ID_DETALLE_TEORICO     NUMBER(10)      NOT NULL,
  ID_EVALUACION          NUMBER(10)      NOT NULL,
  ID_PREGUNTA            NUMBER(10)      NOT NULL,
  ID_RESPUESTA_DADA      NUMBER(10)      NOT NULL,
  ES_CORRECTA            NUMBER(1)       NOT NULL,
  PUNTOS_OBTENIDOS       NUMBER(2)       NOT NULL,
  TIEMPO_RESPUESTA       NUMBER(10),
  CONSTRAINT PK_DETALLE_TEORICO PRIMARY KEY (ID_DETALLE_TEORICO),
  CONSTRAINT FK_DET_TEOR_EVAL FOREIGN KEY (ID_EVALUACION) 
    REFERENCES EVALUACION(ID_EVALUACION) ON DELETE CASCADE,
  CONSTRAINT FK_DET_TEOR_PREG FOREIGN KEY (ID_PREGUNTA) 
    REFERENCES PREGUNTA_TEORICA(ID_PREGUNTA),
  CONSTRAINT FK_DET_TEOR_RESP FOREIGN KEY (ID_RESPUESTA_DADA) 
    REFERENCES RESPUESTA_TEORICA(ID_RESPUESTA),
  CONSTRAINT CK_DET_TEOR_CORRECTA CHECK (ES_CORRECTA IN (0, 1)),
  CONSTRAINT CK_DET_TEOR_PUNTOS CHECK (PUNTOS_OBTENIDOS IN (0, 4)),
  CONSTRAINT UQ_DET_TEOR_EVAL_PREG UNIQUE (ID_EVALUACION, ID_PREGUNTA)
